export function useI18n() {
	const settings = useSettingsStore()
	const locale = computed(() => settings.locale)

	function t(key: keyof (typeof messages)['zh-CN'] | string): string {
		const bundle = messages[settings.locale] ?? messages['zh-CN']
		return bundle[key] ?? messages['zh-CN'][key] ?? key
	}

	return {
		t,
		locale,
	}
}

export function getTransportLabel(
	locale: Locale,
	transport?: 'usb' | 'bluetooth' | 'other',
): string {
	if (transport === 'usb') {
		return messages[locale]['serial.usb']
	}

	if (transport === 'bluetooth') {
		return messages[locale]['serial.bluetooth']
	}

	return messages[locale]['serial.other']
}
